"""Evidence storage adapter (issue #68, plan R-08).

Uploaded incident evidence is written through one small interface so the storage service the
product owner chooses (decision D-3) plugs in without touching the upload endpoint:

    EVIDENCE_STORAGE=disabled  (default) -> uploads answer 503 EVIDENCE_STORAGE_UNAVAILABLE
    EVIDENCE_STORAGE=local     -> files under EVIDENCE_STORAGE_DIR (development, or a server with
                                  a persistent volume; NOT ephemeral containers such as Render)

To add the chosen cloud service, implement EvidenceStorage (put / delete) and register it in
_PROVIDERS. Keys are generated by the server, never taken from the client.
"""

from __future__ import annotations

import os
from abc import ABC, abstractmethod
from pathlib import Path

from app.config import ConfigError, Settings, get_settings


class EvidenceStorageUnavailable(Exception):
    """No storage service is configured, or the configured one cannot be used."""


class EvidenceStorage(ABC):
    name: str

    @abstractmethod
    def put(self, key: str, data: bytes, content_type: str) -> None:
        """Store `data` under `key`. Must not overwrite an existing object."""

    @abstractmethod
    def delete(self, key: str) -> None:
        """Remove `key` if it exists (used to undo a write whose database insert failed)."""


class LocalDiskStorage(EvidenceStorage):
    """Files on the local filesystem, one file per key below `root`."""

    name = "local"

    def __init__(self, root: str | Path):
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if self.root not in path.parents:  # defence in depth: keys are server-generated
            raise ValueError("Evidence key escapes the storage directory")
        return path

    def put(self, key: str, data: bytes, content_type: str) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        # "xb": fail rather than silently replace evidence that is already stored.
        with open(path, "xb") as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


def _local(settings: Settings) -> EvidenceStorage:
    if not settings.evidence_storage_dir:
        raise ConfigError("EVIDENCE_STORAGE=local requires EVIDENCE_STORAGE_DIR")
    return LocalDiskStorage(settings.evidence_storage_dir)


_PROVIDERS = {"local": _local}
SUPPORTED = ("disabled", *_PROVIDERS)


def evidence_storage_problems(settings: Settings) -> list[str]:
    """Configuration errors that must stop startup (an unknown provider is never silently ignored)."""
    if settings.evidence_storage not in SUPPORTED:
        return [f"EVIDENCE_STORAGE={settings.evidence_storage!r} is not supported; use one of: {', '.join(SUPPORTED)}"]
    if settings.evidence_storage == "local" and not settings.evidence_storage_dir:
        return ["EVIDENCE_STORAGE=local requires EVIDENCE_STORAGE_DIR"]
    return []


def storage_enabled(settings: Settings | None = None) -> bool:
    settings = settings or get_settings()
    return settings.evidence_storage in _PROVIDERS and not evidence_storage_problems(settings)


def get_evidence_storage() -> EvidenceStorage:
    settings = get_settings()
    factory = _PROVIDERS.get(settings.evidence_storage)
    if factory is None:
        raise EvidenceStorageUnavailable("No evidence storage service is configured")
    return factory(settings)
